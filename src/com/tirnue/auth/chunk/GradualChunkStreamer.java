package com.tirnue.auth.chunk;

import com.github.retrooper.packetevents.PacketEvents;
import com.github.retrooper.packetevents.event.PacketListenerAbstract;
import com.github.retrooper.packetevents.event.PacketListenerPriority;
import com.github.retrooper.packetevents.event.PacketSendEvent;
import com.github.retrooper.packetevents.protocol.packettype.PacketType;
import com.github.retrooper.packetevents.wrapper.play.server.WrapperPlayServerJoinGame;
import com.github.retrooper.packetevents.wrapper.play.server.WrapperPlayServerUpdateViewDistance;
import com.tirnue.auth.TirnueAuth;
import org.bukkit.Bukkit;
import org.bukkit.entity.Player;
import org.bukkit.event.EventHandler;
import org.bukkit.event.EventPriority;
import org.bukkit.event.Listener;
import org.bukkit.event.player.PlayerChangedWorldEvent;
import org.bukkit.event.player.PlayerJoinEvent;
import org.bukkit.event.player.PlayerLoginEvent;
import org.bukkit.event.player.PlayerQuitEvent;
import org.bukkit.scheduler.BukkitTask;

import java.util.Map;
import java.util.Set;
import java.util.UUID;
import java.util.concurrent.ConcurrentHashMap;

/**
 * Progressively streams chunks ring-by-ring (+1 radius at a time) without ever triggering
 * a client-side render-distance reallocation or shader screen flash.
 *
 * How it works:
 * 1. Clientbound JOIN_GAME and initial UPDATE_VIEW_DISTANCE packets are locked to the full
 *    target view distance (e.g. 14) so the client (and Sodium/Iris shaders) allocates its
 *    chunk storage buffer ONCE and never calls LevelRenderer.allChanged().
 * 2. Server-side sendViewDistance starts at initial-view-distance (3) before the player is
 *    added to the world chunk loader, then increments +1 ring at a time (3 -> 4 -> 5 -> ... -> 14)
 *    so outer rings smoothly add onto already-loaded inner chunks until maxed out.
 * 3. Intermediate UPDATE_VIEW_DISTANCE packets (< targetDistance) generated by server-side
 *    sendViewDistance steps are suppressed via PacketEvents so the client screen never refreshes.
 */
public class GradualChunkStreamer implements Listener {
    private final TirnueAuth plugin;
    private final Map<UUID, BukkitTask> activeStreams = new ConcurrentHashMap<>();
    private final Map<UUID, Integer> targetDistances = new ConcurrentHashMap<>();
    private final Set<UUID> clientRadiusInitialized = ConcurrentHashMap.newKeySet();
    private PacketListenerAbstract packetListener;

    public GradualChunkStreamer(TirnueAuth plugin) {
        this.plugin = plugin;
        registerPacketInterceptor();
    }

    private void registerPacketInterceptor() {
        if (!Bukkit.getPluginManager().isPluginEnabled("packetevents")) {
            return;
        }
        try {
            this.packetListener = new PacketListenerAbstract(PacketListenerPriority.NORMAL) {
                @Override
                public void onPacketSend(PacketSendEvent event) {
                    if (!plugin.getConfig().getBoolean("gradual-chunks.enabled", true)) {
                        return;
                    }
                    if (event.getPacketType() == PacketType.Play.Server.JOIN_GAME) {
                        UUID uuid = event.getUser() != null ? event.getUser().getUUID() : null;
                        int target = getConfiguredTarget(uuid);
                        WrapperPlayServerJoinGame join = new WrapperPlayServerJoinGame(event);
                        if (join.getViewDistance() < target) {
                            join.setViewDistance(target);
                            event.markForReEncode(true);
                        }
                        if (uuid != null) {
                            clientRadiusInitialized.add(uuid);
                        }
                    } else if (event.getPacketType() == PacketType.Play.Server.UPDATE_VIEW_DISTANCE) {
                        UUID uuid = event.getUser() != null ? event.getUser().getUUID() : null;
                        if (uuid == null) {
                            return;
                        }
                        int target = getConfiguredTarget(uuid);
                        WrapperPlayServerUpdateViewDistance pkt = new WrapperPlayServerUpdateViewDistance(event);
                        int sentDist = pkt.getViewDistance();

                        // If we are actively streaming rings (or packet is below target):
                        if (activeStreams.containsKey(uuid) || sentDist < target) {
                            if (clientRadiusInitialized.contains(uuid)) {
                                // Client already has its chunk cache sized to target; suppress intermediate
                                // radius changes so Sodium/Iris/Vanilla never refreshes the screen!
                                event.setCancelled(true);
                            } else {
                                pkt.setViewDistance(target);
                                event.markForReEncode(true);
                                clientRadiusInitialized.add(uuid);
                            }
                        } else if (sentDist >= target && clientRadiusInitialized.contains(uuid)) {
                            // Final step reached target; client is already at target, so suppress duplicate packet
                            event.setCancelled(true);
                        }
                    }
                }
            };
            PacketEvents.getAPI().getEventManager().registerListener(this.packetListener);
        } catch (Throwable t) {
            plugin.getLogger().warning("Failed to register GradualChunkStreamer packet interceptor: " + t.getMessage());
        }
    }

    private int getConfiguredTarget(UUID uuid) {
        if (uuid != null) {
            Integer cached = targetDistances.get(uuid);
            if (cached != null) {
                return cached;
            }
        }
        return plugin.getConfig().getInt("gradual-chunks.target-view-distance", 14);
    }

    public void startStream(Player player) {
        if (!plugin.getConfig().getBoolean("gradual-chunks.enabled", true)) {
            return;
        }

        UUID uuid = player.getUniqueId();
        stopStream(uuid);

        int initialDistance = Math.max(2, plugin.getConfig().getInt("gradual-chunks.initial-view-distance", 3));
        int configuredTarget = plugin.getConfig().getInt("gradual-chunks.target-view-distance", 14);
        int worldDistance = player.getWorld() != null ? player.getWorld().getViewDistance() : configuredTarget;
        final int targetDistance = Math.max(initialDistance, Math.min(configuredTarget, worldDistance));
        targetDistances.put(uuid, targetDistance);

        if (targetDistance <= initialDistance) {
            return;
        }

        // Clamp server-side sendViewDistance ONLY (never touch simulation/load viewDistance)
        try {
            player.setSendViewDistance(initialDistance);
        } catch (Throwable t) {
            plugin.getLogger().warning("Could not set initial send view distance for " + player.getName() + ": " + t.getMessage());
            return;
        }

        // Step +1 chunk ring every 8 ticks (0.4s) so chunks smoothly expand outward around already-loaded chunks
        long totalTicks = Math.max(20L, plugin.getConfig().getLong("gradual-chunks.ticks-per-stage", 30L) * 3L);
        int rings = Math.max(1, targetDistance - initialDistance);
        long ticksPerRing = Math.max(6L, Math.min(12L, totalTicks / rings));

        BukkitTask task = Bukkit.getScheduler().runTaskTimer(plugin, new Runnable() {
            private int currentRadius = initialDistance;

            @Override
            public void run() {
                if (!player.isOnline()) {
                    stopStream(uuid);
                    return;
                }

                currentRadius++;
                try {
                    if (currentRadius < targetDistance) {
                        player.setSendViewDistance(currentRadius);
                    } else {
                        player.setSendViewDistance(targetDistance);
                        // Hand back to world default (-1) once fully caught up
                        if (targetDistance >= worldDistance) {
                            player.setSendViewDistance(-1);
                            player.setViewDistance(-1);
                        }
                        stopStream(uuid);
                    }
                } catch (Throwable t) {
                    stopStream(uuid);
                }
            }
        }, ticksPerRing, ticksPerRing);

        activeStreams.put(uuid, task);
    }

    public void stopStream(UUID uuid) {
        BukkitTask task = activeStreams.remove(uuid);
        if (task != null) {
            try {
                task.cancel();
            } catch (Throwable ignored) {}
        }
    }

    public void cancelAll() {
        for (BukkitTask task : activeStreams.values()) {
            try {
                task.cancel();
            } catch (Throwable ignored) {}
        }
        activeStreams.clear();
        targetDistances.clear();
        clientRadiusInitialized.clear();
        if (this.packetListener != null) {
            try {
                PacketEvents.getAPI().getEventManager().unregisterListener(this.packetListener);
            } catch (Throwable ignored) {}
            this.packetListener = null;
        }
    }

    @EventHandler(priority = EventPriority.MONITOR, ignoreCancelled = true)
    public void onPlayerLogin(PlayerLoginEvent event) {
        if (!plugin.getConfig().getBoolean("gradual-chunks.enabled", true)) {
            return;
        }
        Player player = event.getPlayer();
        int initialDistance = Math.max(2, plugin.getConfig().getInt("gradual-chunks.initial-view-distance", 3));
        int configuredTarget = plugin.getConfig().getInt("gradual-chunks.target-view-distance", 14);
        targetDistances.put(player.getUniqueId(), configuredTarget);
        try {
            // Pre-clamp sendViewDistance before ServerLevel.addNewPlayer runs so outer chunks aren't queued & unloaded
            player.setSendViewDistance(initialDistance);
        } catch (Throwable ignored) {}
    }

    @EventHandler(priority = EventPriority.MONITOR)
    public void onPlayerJoin(PlayerJoinEvent event) {
        startStream(event.getPlayer());
    }

    @EventHandler(priority = EventPriority.MONITOR, ignoreCancelled = true)
    public void onWorldChange(PlayerChangedWorldEvent event) {
        startStream(event.getPlayer());
    }

    @EventHandler(priority = EventPriority.MONITOR)
    public void onPlayerQuit(PlayerQuitEvent event) {
        UUID uuid = event.getPlayer().getUniqueId();
        stopStream(uuid);
        targetDistances.remove(uuid);
        clientRadiusInitialized.remove(uuid);
    }
}
